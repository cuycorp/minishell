#include "minishell.h"

int	ft_is_special_char(char c)
{
	return (c == '!' || c == '.' || c == ',' || c == ';' || c == ':' || c == '?'
		|| c == '~' || c == '_' || c == '@' || c == '+' || c == '/' || c == '='
		|| c == '[' || c == ']' || c == '*' || c == '-' || c == '\\' || c == '|'
		|| c == '<' || c == '>' || c == '$' || c == '^' || c == '&' || c == '#'
		|| c == '%' || c == '(' || c == ')' || c == '{' || c == '}');
}
