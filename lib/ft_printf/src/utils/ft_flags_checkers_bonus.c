#include "ft_printf.h"

int	ft_isspecifier(char c)
{
	if (c == 'c' || c == 's' || c == 'p' || c == 'd' || c == 'i' || c == 'u' \
		|| c == 'x' || c == 'X' || c == '%')
		return (1);
	return (0);
}

int	ft_isflags(char c)
{
	if (c == '.' || c == '#' || c == ' ' || c == '+' || c == '-' || c == '*')
		return (1);
	return (0);
}
